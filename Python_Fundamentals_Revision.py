# 1. Arithmetic Operators

a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)


# 2. Conditional Statements

x = 8

if x > 10:
    print("A")
elif x > 5:
    print("B")
else:
    print("C")


# 3. For Loop

for i in range(1, 6):
    print(i)


# 4. range() with Step

for i in range(2, 11, 2):
    print(i)


