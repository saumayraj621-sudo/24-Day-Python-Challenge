# Day 01 - Loops

# For loop
for i in range(5):
    print(i)


# Start and stop
for i in range(2, 7):
    print(i)


# Step
for i in range(1, 10, 2):
    print(i)


# While loop
i = 1

while i <= 5:
    print(i)
    i = i + 1


# Even numbers
i = 1

while i <= 10:
    if i % 2 == 0:
        print(i)
    i = i + 1
